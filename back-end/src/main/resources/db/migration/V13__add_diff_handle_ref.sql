-- ============================================
-- Flyway V13: 差异处置补凭证字段
-- ============================================
-- 背景：V12 的处置只有「状态 + 方式」两个标签，没有任何校验也没有回查入口，
-- 于是出现一个更干净的"差异消失方式"——用户点了「转报废」，但根本没去提交报废单，
-- 系统照样记成已处置，这条差异从此不在待处置列表里，而资产还在账上。
-- 从"没人看"变成了"看起来处理过了"，比原来更危险。
--
-- 本次配套（应用层）：
--   1. 处置时可填关联单号，作为"确实处理过"的凭证
--   2. 新增已处置列表查询，处置记录可回看（谁、何时、什么方式、关联哪张单）
--   3. 新增撤销处置，误点可退回待处置
--
-- 单号设为可空：人工确认（MANUAL）这类处置本来就没有单据，
-- 强制必填会把流程卡死。是否强制由前端按处置方式提示，不在库里做硬约束。

ALTER TABLE check_record
    ADD COLUMN diff_handle_ref VARCHAR(64) NULL
        COMMENT '关联单据号：报废单号 / 新资产编号，作为处置凭证' AFTER diff_handle_type;
